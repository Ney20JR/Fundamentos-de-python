# Tema 3: Operadores básicos

# Ejercicio 1: área y perímetro de un rectángulo (base 8, altura 5)
base = 8 # int
altura = 5 # int
print ("Área:", base * altura)
print ("Perímetro:", 2 * (base + altura))

# Ejercicio 2: ¿es par?
numero = 14 # int
print (numero, "es par:", numero % 2 == 0)

# Ejercicio 3: 100 grados Celsius a Fahrenheit
celsius = 100 # int
fahrenheit = celsius * 9 / 5 + 32 # float
print (celsius, "°C =", fahrenheit, "°F")

# Ejercicio 4: ¿está entre 10 y 20?
n = 15 # int
print (n, "está entre 10 y 20:", n >= 10 and n <= 20)
